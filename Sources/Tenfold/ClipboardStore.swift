import AppKit
import Combine

/// Watches the general pasteboard and keeps the 50 most recent text/image/file items (in memory only).
@MainActor
final class ClipboardStore: ObservableObject {
    static let maxItems = 50
    /// Images are heavy – only this many unpinned ones are kept.
    static let maxImages = 10

    @Published private(set) var items: [ClipItem] = []
    @Published private(set) var lastCopiedID: UUID?
    @Published var query = ""

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?

    /// Markers used by password managers & co. (see nspasteboard.org) – never stored.
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword"
    ]

    /// Apps whose copies are never stored (matched against bundle ID + app name, case-insensitive).
    /// Covers Enpass regardless of its exact bundle ID (direct download vs. App Store build).
    static let passwordManagerHints = ["enpass", "1password", "bitwarden", "keepass", "lastpass",
                                       "dashlane", "nordpass", "proton.pass", "com.apple.keychainaccess",
                                       "com.apple.passwords"]

    private static let pinnedKey = "clipboard.pinnedTexts"

    init() {
        lastChangeCount = pasteboard.changeCount
        // Pinned text items survive restarts (images only for the session).
        let pinned = UserDefaults.standard.stringArray(forKey: Self.pinnedKey) ?? []
        items = pinned.prefix(Self.maxItems).map { ClipItem(content: .text($0), date: Date(), isPinned: true) }
    }

    /// True if the app in front (the one that most likely just copied) is a password manager.
    private func copiedFromPasswordManager() -> Bool {
        guard UserDefaults.standard.bool(forKey: Prefs.ignorePasswordManagers),
              let app = NSWorkspace.shared.frontmostApplication else { return false }
        let haystack = "\(app.bundleIdentifier ?? "") \(app.localizedName ?? "")".lowercased()
        return Self.passwordManagerHints.contains { haystack.contains($0) }
    }

    func start() {
        timer?.invalidate()
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        capture()
    }

    private func capture() {
        let types = pasteboard.types?.map(\.rawValue) ?? []
        if types.contains(where: { ignoredTypes.contains($0) }) { return }
        if copiedFromPasswordManager() { return }

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                             options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            insert(.files(urls))
        } else if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            insert(.text(text))
        } else if pasteboard.canReadObject(forClasses: [NSImage.self], options: nil),
                  let image = NSImage(pasteboard: pasteboard) {
            insert(.image(image))
        }
    }

    private func insert(_ content: ClipItem.Content) {
        if case .text(let new) = content {
            items.removeAll {
                if case .text(let old) = $0.content { return !$0.isPinned && old == new }
                return false
            }
        }
        if case .files(let new) = content {
            items.removeAll {
                if case .files(let old) = $0.content { return !$0.isPinned && old == new }
                return false
            }
        }
        if case .text(let new) = content,
           let pinned = items.firstIndex(where: { if case .text(let old) = $0.content { return $0.isPinned && old == new }; return false }) {
            _ = pinned        // already kept as a pinned item – don't duplicate
            return
        }
        var thumb: NSImage?
        var size: CGSize?
        if case .files(let urls) = content, let first = urls.first { (thumb, size) = Self.thumbnail(for: first) }
        items.insert(ClipItem(content: content, date: Date(), thumbnail: thumb, pixelSize: size), at: 0)
        trim()
    }

    /// Keeps at most `maxItems`; pinned items are never dropped (oldest unpinned go first).
    private func trim() {
        while items.count > Self.maxItems, let index = items.lastIndex(where: { !$0.isPinned }) {
            items.remove(at: index)
        }
        let isImage: (ClipItem) -> Bool = { if case .image = $0.content { return !$0.isPinned }; return false }
        while items.filter(isImage).count > Self.maxImages, let index = items.lastIndex(where: isImage) {
            items.remove(at: index)
        }
    }

    /// Downsampled preview + pixel size for image files (ImageIO, never decodes the full image);
    /// Finder icon for everything else.
    private static func thumbnail(for url: URL) -> (NSImage, CGSize?) {
        let options = [kCGImageSourceCreateThumbnailFromImageAlways: true,
                       kCGImageSourceCreateThumbnailWithTransform: true,
                       kCGImageSourceThumbnailMaxPixelSize: 160] as CFDictionary
        if let source = CGImageSourceCreateWithURL(url as CFURL, nil),
           let cg = CGImageSourceCreateThumbnailAtIndex(source, 0, options) {
            let props = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any]
            let size = (props?[kCGImagePropertyPixelWidth] as? Int).flatMap { w in
                (props?[kCGImagePropertyPixelHeight] as? Int).map { CGSize(width: w, height: $0) }
            }
            return (NSImage(cgImage: cg, size: NSSize(width: cg.width, height: cg.height)), size)
        }
        return (NSWorkspace.shared.icon(forFile: url.path), nil)
    }

    /// Items matching the search field (all items when empty).
    var filtered: [ClipItem] {
        let q = query.trimmingCharacters(in: .whitespaces)
        guard !q.isEmpty else { return items }
        return items.filter { $0.searchText.localizedCaseInsensitiveContains(q) }
    }

    func togglePin(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].isPinned.toggle()
        savePinned()
    }

    private func savePinned() {
        let texts: [String] = items.compactMap {
            guard $0.isPinned, case .text(let s) = $0.content else { return nil }
            return s
        }
        UserDefaults.standard.set(texts, forKey: Self.pinnedKey)
    }

    /// Puts the item back on the clipboard (user then presses ⌘V).
    func copy(_ item: ClipItem) {
        pasteboard.clearContents()
        switch item.content {
        case .text(let s): pasteboard.setString(s, forType: .string)
        case .image(let img): pasteboard.writeObjects([img])
        case .files(let urls): pasteboard.writeObjects(urls as [NSURL])
        }
        lastChangeCount = pasteboard.changeCount   // don't re-capture our own write

        if let idx = items.firstIndex(where: { $0.id == item.id }) {
            let moved = items.remove(at: idx)
            items.insert(moved, at: 0)
        }
        lastCopiedID = item.id
        Task { @MainActor [weak self] in
            try? await Task.sleep(nanoseconds: 1_200_000_000)
            if self?.lastCopiedID == item.id { self?.lastCopiedID = nil }
        }
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        savePinned()
    }

    /// Clears the history but keeps pinned items.
    func clear() { items.removeAll { !$0.isPinned } }
}
